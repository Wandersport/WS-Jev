    ilsa_prob: float
    jev_blind_prob: float | None
    jev_market_aware_prob: float | None
    market_brier: float
    ilsa_brier: float
    jev_blind_brier: float | None
    jev_market_aware_brier: float | None
    market_log_loss: float
    ilsa_log_loss: float
    jev_blind_log_loss: float | None
    jev_market_aware_log_loss: float | None
    metadata: dict[str, Any] = field(default_factory=dict)

